#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
if (!process.argv[2]) {
  console.error("Usage: node scripts/generate-airline-logos.mjs <path/to/airline_logo_bitmaps.cpp>");
  process.exit(1);
}
const input = resolve(process.argv[2]);
const output = resolve(root, "src/lib/airlineLogoData.ts");

const source = readFileSync(input, "utf8");

const assetPattern =
  /\/\/ ([A-Z]{3}): (\S+)\r?\n\/\/ \d+x\d+, \d+ bytes per row\.\r?\nstatic const uint8_t kLogo([A-Z]{3})Bits\[\] PROGMEM = \{([^}]*)\};/g;
const assets = new Map();
for (const match of source.matchAll(assetPattern)) {
  const [, icao, url, arrayIcao, body] = match;
  if (icao !== arrayIcao) throw new Error(`Mismatched asset ${icao}/${arrayIcao}`);
  const bytes = [...body.matchAll(/0x([0-9A-Fa-f]{2})/g)].map((m) => parseInt(m[1], 16));
  assets.set(icao, { url, bytes });
}

const entries = [...source.matchAll(/\{"([A-Z]{3})",\s*(\d+),\s*(\d+),\s*kLogo([A-Z]{3})Bits\}/g)];
if (entries.length === 0) throw new Error("No logo table entries found");

const logos = entries.map(([, icao, w, h, arrayIcao]) => {
  if (icao !== arrayIcao) throw new Error(`Table entry ${icao} points at ${arrayIcao}`);
  const asset = assets.get(icao);
  if (!asset) throw new Error(`No bitmap data found for ${icao}`);
  const width = Number(w);
  const height = Number(h);
  const expected = Math.ceil(width / 8) * height;
  if (asset.bytes.length !== expected) {
    throw new Error(`${icao}: expected ${expected} bytes for ${width}x${height}, got ${asset.bytes.length}`);
  }
  return {
    icao,
    width,
    height,
    source: asset.url,
    data: Buffer.from(asset.bytes).toString("base64"),
  };
});

const lines = logos.map(
  (l) =>
    `  { icao: ${JSON.stringify(l.icao)}, width: ${l.width}, height: ${l.height}, source: ${JSON.stringify(l.source)},\n    data: ${JSON.stringify(l.data)} },`,
);

writeFileSync(
  output,
  `// Generated by scripts/generate-airline-logos.mjs from the firmware source

export interface AirlineLogoAsset {
  icao: string;
  width: number;
  height: number;
  source: string;
  data: string;
}

export const AIRLINE_LOGO_ASSETS: AirlineLogoAsset[] = [
${lines.join("\n")}
];
`,
);

console.log(`Wrote ${logos.length} logos to ${output}`);
